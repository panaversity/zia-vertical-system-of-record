"""Unit contract for `vsor/site_runtime.py` — written red-first from
specs/vsor/build/spec.md ("The runtime shell — materialization and staleness",
"Preconditions, stated not assumed").

Public surface these tests define:

- `probe_node_version() -> str | None` — the measured node version, no leading `v`
  (e.g. "24.4.1"); None when node is not on PATH. Verbs call it as a module attribute
  (`site_runtime.probe_node_version()`) so tests can monkeypatch the probe.
- `check_node(version: str | None) -> None` — raises `CommandError("missing-runtime", …)`
  (exit 3) when node is absent OR too old (< 20); the remedy names what was measured
  and where to install (nodejs.org).
- `ensure_runtime(project_root: Path) -> Path` — materializes `.vsor/site-runtime/` and
  returns it; also a module attribute, the monkeypatch seam for the command tests.
- `write_stamp(runtime_dir, *, vsor_version, package_json, lock, app) -> None` — writes
  `.materialized.json` = {vsor, package_json_sha256, lock_sha256, app_sha256}, only ever
  AFTER a successful `npm ci` (an interrupted install never writes it).
- `stamp_is_current(runtime_dir, *, vsor_version, package_json, lock, app) -> bool` —
  reuse the shell iff the stamp matches the freshly generated bytes; absence, mismatch,
  or a corrupt stamp all mean wipe-and-rematerialize, never a crash.
- `library_tarballs(package_json) -> tuple[str, ...]` — the `file:./…tgz` dependencies
  the shell manifest names, which is what materialization copies out of the wheel.
- `runtime_env()` — the environment the verbs run Docusaurus under: the app's corpus and
  site seams pointed at the copies inside the shell.

`app_sha256` joined the stamp on 2026-08-14, when the shell became the forked app: the
app is UNPACKED over the shell rather than installed into node_modules, so a changed fork
with an unchanged dependency set leaves package.json and package-lock.json byte-identical
and the old shell would have been reused as current. The library tarballs need no hash
here — npm records their sha512 in the lockfile, so changing one moves `lock_sha256`.
"""

import hashlib
import json
from pathlib import Path

import pytest
from vsor import site_runtime
from vsor.errors import CommandError

VSOR_VERSION = "0.1.0"
PACKAGE_JSON = b'{"name": "site-runtime-shell", "private": true}\n'
LOCKFILE = b'{"lockfileVersion": 3}\n'
APP = b"not really a tarball, but bytes are bytes\n"


def current(
    runtime_dir: Path,
    *,
    vsor_version: str = VSOR_VERSION,
    package_json: bytes = PACKAGE_JSON,
    lock: bytes = LOCKFILE,
    app: bytes = APP,
) -> bool:
    result = site_runtime.stamp_is_current(
        runtime_dir, vsor_version=vsor_version, package_json=package_json, lock=lock, app=app
    )
    assert isinstance(result, bool)
    return result


def write(runtime_dir: Path) -> None:
    site_runtime.write_stamp(
        runtime_dir, vsor_version=VSOR_VERSION, package_json=PACKAGE_JSON, lock=LOCKFILE, app=APP
    )


def test_module_seams_exist() -> None:
    """The command layer reaches these through the module object — the monkeypatch seam."""
    assert callable(site_runtime.probe_node_version)
    assert callable(site_runtime.ensure_runtime)


# ------------------------------------------------------------------ the .materialized.json stamp


def test_absent_stamp_means_rematerialize(tmp_path: Path) -> None:
    assert current(tmp_path) is False


def test_stamp_round_trip_means_reuse(tmp_path: Path) -> None:
    write(tmp_path)
    assert current(tmp_path) is True


def test_stamp_file_shape_is_the_spec_shape(tmp_path: Path) -> None:
    """`.materialized.json` carries exactly
    {vsor, package_json_sha256, lock_sha256, app_sha256}."""
    write(tmp_path)
    data = json.loads((tmp_path / ".materialized.json").read_text(encoding="utf-8"))
    assert data == {
        "vsor": VSOR_VERSION,
        "package_json_sha256": hashlib.sha256(PACKAGE_JSON).hexdigest(),
        "lock_sha256": hashlib.sha256(LOCKFILE).hexdigest(),
        "app_sha256": hashlib.sha256(APP).hexdigest(),
    }


def test_changed_package_json_is_stale(tmp_path: Path) -> None:
    write(tmp_path)
    assert current(tmp_path, package_json=PACKAGE_JSON + b" ") is False


def test_changed_lockfile_is_stale(tmp_path: Path) -> None:
    write(tmp_path)
    assert current(tmp_path, lock=LOCKFILE + b" ") is False


def test_changed_app_tarball_is_stale(tmp_path: Path) -> None:
    """The shell IS the app, unpacked — so a rebuilt fork with an unchanged dependency
    set must still invalidate the shell. Nothing else in the stamp would move."""
    write(tmp_path)
    assert current(tmp_path, app=APP + b" ") is False


def test_upgraded_vsor_is_stale(tmp_path: Path) -> None:
    """This is what keeps an upgraded vsor from silently building with old JS."""
    write(tmp_path)
    assert current(tmp_path, vsor_version="0.2.0") is False


def test_partial_install_without_stamp_is_stale(tmp_path: Path) -> None:
    """An interrupted `npm ci` leaves node_modules debris but never a stamp —
    debris alone must not count as materialized."""
    (tmp_path / "node_modules" / ".package-lock.json").parent.mkdir(parents=True)
    (tmp_path / "node_modules" / ".package-lock.json").write_bytes(b"{}")
    (tmp_path / "package.json").write_bytes(PACKAGE_JSON)
    assert current(tmp_path) is False


def test_corrupt_stamp_is_stale_never_a_crash(tmp_path: Path) -> None:
    (tmp_path / ".materialized.json").write_text("not json at all {", encoding="utf-8")
    assert current(tmp_path) is False


